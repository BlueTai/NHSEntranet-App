@Composable
fun ExpandedNativeForm() {
    var parentOccupation by remember { mutableStateOf("") }
    var allergies by remember { mutableStateOf("") }
    var transportDriver by remember { mutableStateOf("") }
    
    // Auto-populated fields
    var studentName by remember { mutableStateOf("John Doe") }

    Column(modifier = Modifier.padding(16.dp).fillMaxSize().verticalScroll(rememberScrollState())) {
        Text("Student Medical & Transport Update", style = MaterialTheme.typography.titleMedium)
        Spacer(modifier = Modifier.height(16.dp))
        
        OutlinedTextField(value = studentName, onValueChange = {}, label = { Text("Student Name (Auto-populated)") }, enabled = false, modifier = Modifier.fillMaxWidth())
        Spacer(modifier = Modifier.height(8.dp))
        
        OutlinedTextField(value = parentOccupation, onValueChange = { parentOccupation = it }, label = { Text("Parent Occupation") }, modifier = Modifier.fillMaxWidth())
        Spacer(modifier = Modifier.height(8.dp))
        
        OutlinedTextField(value = allergies, onValueChange = { allergies = it }, label = { Text("Student Allergies") }, modifier = Modifier.fillMaxWidth())
        Spacer(modifier = Modifier.height(8.dp))
        
        OutlinedTextField(value = transportDriver, onValueChange = { transportDriver = it }, label = { Text("Transport Driver Name & Contact") }, modifier = Modifier.fillMaxWidth())
        
        Spacer(modifier = Modifier.height(24.dp))
        Button(onClick = { /* TODO: POST /api/forms/submit and trigger PDF generation on backend */ }, modifier = Modifier.fillMaxWidth()) {
            Text("Save & Download as PDF")
        }
    }
}

// -----------------------------------------------------
// GOOGLE FORMS INTEGRATION (Section 4 Requirement)
// -----------------------------------------------------
@Composable
fun GoogleFormsWebView() {
    // Replace with the embed URL generated by the Admin
    val googleFormUrl = "https://docs.google.com/forms/d/e/1FAIpQLSf.../viewform?embedded=true"

    AndroidView(
        modifier = Modifier.fillMaxSize(),
        factory = { context ->
            WebView(context).apply {
                layoutParams = ViewGroup.LayoutParams(
                    ViewGroup.LayoutParams.MATCH_PARENT,
                    ViewGroup.LayoutParams.MATCH_PARENT
                )
                settings.javaScriptEnabled = true
                webViewClient = WebViewClient() // Prevents opening in external browser
                loadUrl(googleFormUrl)
            }
        }
    )
}
